package zxingbench.corpus;

import java.util.ArrayList;
import java.util.List;

/**
 * The benchmark dataset manifest.
 *
 * <p>Parsed with a small hand-written reader rather than a JSON library: the benchmark
 * must not drag a dependency into a build whose point is reproducibility, and the
 * manifest is machine-generated by benchmark/dataset/build_manifest.py, so its shape is
 * fixed.
 */
public final class Manifest {

  public static final class Sample {
    public String sampleId;
    public String path;
    public String sha256;
    public int width;
    public int height;
    public String expectedFormat;   // null for negative samples
    public String expectedText;     // null for negative samples
    public List<String> sceneTags = new ArrayList<>();

    public boolean isNegative() {
      return expectedFormat == null;
    }
  }

  public final String datasetHash;
  public final List<Sample> samples;

  private Manifest(String datasetHash, List<Sample> samples) {
    this.datasetHash = datasetHash;
    this.samples = samples;
  }

  /**
   * Parses the manifest text.
   *
   * <p>Takes the text rather than a file so that the device runner can read it from
   * wherever the corpus was pushed to without this module touching {@code java.nio.file},
   * which an Android library at minSdk 21 cannot use.
   */
  public static Manifest parse(String json) {
    Json.Value root = Json.parse(json);
    List<Sample> samples = new ArrayList<>();
    for (Json.Value v : root.get("samples").array()) {
      Sample s = new Sample();
      s.sampleId = v.get("sample_id").string();
      s.path = v.get("path").string();
      s.sha256 = v.get("sha256").string();
      s.width = (int) v.get("width").number();
      s.height = (int) v.get("height").number();
      s.expectedFormat = v.get("expected_format").isNull() ? null : v.get("expected_format").string();
      s.expectedText = v.get("expected_text").isNull() ? null : v.get("expected_text").string();
      for (Json.Value t : v.get("scene_tags").array()) {
        s.sceneTags.add(t.string());
      }
      samples.add(s);
    }
    return new Manifest(root.get("dataset_hash").string(), samples);
  }
}
